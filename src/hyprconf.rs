//! Clawd's part of the Hyprland config: ~/.config/hypr/clawd.lua, generated
//! from Clawd's settings (hotkeys, its layer rule, autostart). The main
//! hyprland.lua loads it with `pcall(require, "clawd")`.

use crate::state::Settings;
use std::path::PathBuf;
use std::process::Command;

fn path() -> Option<PathBuf> {
    let dir = dirs::config_dir()?.join("hypr");
    dir.is_dir().then(|| dir.join("clawd.lua"))
}

/// Whether hyprland.lua loads clawd.lua (otherwise hotkeys can't work).
pub fn is_loaded() -> bool {
    dirs::config_dir()
        .and_then(|d| std::fs::read_to_string(d.join("hypr/hyprland.lua")).ok())
        .is_some_and(|text| text.lines().any(|l| l.trim_start().starts_with("pcall(require, \"clawd\")")))
}

/// A key combo Hyprland understands: modifiers joined with " + " and a key,
/// e.g. "SUPER + CTRL + A". Returns the normalized form.
pub fn parse_combo(combo: &str) -> Option<String> {
    const MODS: [&str; 4] = ["SUPER", "CTRL", "ALT", "SHIFT"];
    let parts: Vec<String> = combo.split('+').map(|p| p.trim().to_string()).filter(|p| !p.is_empty()).collect();
    let (key, mods) = parts.split_last()?;
    let mods: Vec<String> = mods.iter().map(|m| m.to_uppercase()).collect();
    if !mods.iter().all(|m| MODS.contains(&m.as_str())) || mods.is_empty() {
        return None;
    }
    if key.is_empty() || !key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return None;
    }
    let key = if key.len() == 1 { key.to_uppercase() } else { key.clone() };
    // Canonical modifier order.
    let mut ordered: Vec<&str> = MODS.iter().copied().filter(|m| mods.iter().any(|x| x == m)).collect();
    ordered.dedup();
    Some(format!("{} + {key}", ordered.join(" + ")))
}

fn lua_string(s: &str) -> String {
    format!("{s:?}") // Rust's escaping is valid Lua for these simple strings
}

/// The generated Lua for `settings`.
pub fn render(settings: &Settings, clawd: &str) -> String {
    let hk = &settings.hotkeys;
    let binds = [
        (&hk.quick_ask, "ask", "Clawd: Quick ask at the cursor"),
        (&hk.explain, "explain", "Clawd: Explain the selected text"),
        (&hk.screenshot, "screenshot", "Clawd: Screenshot a region for Claude"),
        (&hk.screenshot_window, "screenshot-window", "Clawd: Screenshot the focused window for Claude"),
        (&hk.toggle, "toggle", "Clawd: Show or hide Clawd"),
        (&hk.voice, "voice", "Clawd: Start or stop voice input"),
    ];
    let mut lua = String::from(
        "-- Generated by Clawd from its settings; changes here are overwritten.\n\
         -- Change hotkeys and autostart in Clawd's settings instead.\n\n",
    );
    lua.push_str(&format!("local clawd = {}\n\n", lua_string(clawd)));
    for (combo, command, description) in binds {
        if let Some(combo) = parse_combo(combo) {
            lua.push_str(&format!(
                "hl.bind({}, hl.dsp.exec_cmd(clawd .. \" {command}\"), {{ description = {} }})\n",
                lua_string(&combo),
                lua_string(description)
            ));
        }
    }
    lua.push_str(
        "\n-- Clawd moves by changing its layer margins; animating that makes it lag.\n\
         hl.layer_rule({ name = \"clawd\", match = { namespace = \"^clawd\" }, no_anim = true })\n",
    );
    if settings.autostart {
        lua.push_str("\nhl.on(\"hyprland.start\", function()\n\thl.exec_cmd(clawd .. \" toggle\")\nend)\n");
    }
    lua
}

/// Writes clawd.lua and reloads Hyprland. Returns config errors, if any.
pub fn apply(settings: &Settings) -> Result<(), String> {
    let path = path().ok_or("no ~/.config/hypr folder")?;
    // The installed copy, not whatever build happens to be running.
    let installed = dirs::home_dir().map(|h| h.join(".local/bin/clawd")).filter(|p| p.exists());
    let clawd = installed.map_or_else(std::env::current_exe, Ok).map_err(|e| e.to_string())?;
    let lua = render(settings, &clawd.to_string_lossy());
    if std::fs::read_to_string(&path).ok().as_deref() == Some(lua.as_str()) {
        return Ok(());
    }
    std::fs::write(&path, lua).map_err(|e| e.to_string())?;
    let _ = Command::new("hyprctl").arg("reload").output();
    let errors = Command::new("hyprctl").arg("configerrors").output().map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string());
    match errors {
        Ok(e) if !e.is_empty() && e != "ok" => Err(e),
        _ => Ok(()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn combos() {
        assert_eq!(parse_combo("super + a").as_deref(), Some("SUPER + A"));
        assert_eq!(parse_combo("SHIFT+SUPER+ALT + a").as_deref(), Some("SUPER + ALT + SHIFT + A"));
        assert_eq!(parse_combo("SUPER + F5").as_deref(), Some("SUPER + F5"));
        assert_eq!(parse_combo("A"), None); // needs a modifier
        assert_eq!(parse_combo("HYPER + A"), None);
        assert_eq!(parse_combo("SUPER + a\"); os.execute(\"x"), None);
        assert_eq!(parse_combo(""), None);
    }

    #[test]
    fn renders_binds_rule_and_autostart() {
        let mut settings = Settings::default();
        settings.hotkeys.voice = String::new(); // no hotkey
        let lua = render(&settings, "/home/u/.local/bin/clawd");
        assert!(lua.contains(r#"hl.bind("SUPER + A", hl.dsp.exec_cmd(clawd .. " ask"), { description = "Clawd: Quick ask at the cursor" })"#), "{lua}");
        assert!(!lua.contains(" voice\""));
        assert!(lua.contains("no_anim = true"));
        assert!(!lua.contains("hyprland.start"));
        settings.autostart = true;
        assert!(render(&settings, "/x").contains("hl.on(\"hyprland.start\""));
    }
}
